from app.core.permissions import (
    EXECUTE_VERIFICATION_ROLES,
    MANAGE_MEMBER_ROLES,
    MANAGE_PROJECT_ROLES,
    MANAGE_TEST_ASSET_ROLES,
    PROJECT_ROLE_DEVELOPER,
    PROJECT_ROLE_MANAGER,
    PROJECT_ROLE_QA_LEAD,
    PROJECT_ROLE_TESTER,
    PROJECT_ROLE_VIEWER,
    ROLE_CAPABILITIES,
    VIEW_PROJECT_ROLES,
)


def test_role_capabilities_drive_permission_groups():
    assert set(VIEW_PROJECT_ROLES) == set(ROLE_CAPABILITIES)
    assert PROJECT_ROLE_TESTER in EXECUTE_VERIFICATION_ROLES
    assert PROJECT_ROLE_DEVELOPER not in EXECUTE_VERIFICATION_ROLES
    assert PROJECT_ROLE_QA_LEAD in MANAGE_TEST_ASSET_ROLES
    assert PROJECT_ROLE_TESTER not in MANAGE_TEST_ASSET_ROLES
    assert PROJECT_ROLE_MANAGER in MANAGE_PROJECT_ROLES
    assert PROJECT_ROLE_MANAGER in MANAGE_MEMBER_ROLES
    assert PROJECT_ROLE_VIEWER not in MANAGE_MEMBER_ROLES
